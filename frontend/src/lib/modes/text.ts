export type ModeId = 'video' | 'read' | 'podcast' | 'type' | 'vocab' | 'handout';

export const MODE_IDS: readonly ModeId[] = ['video', 'read', 'podcast', 'type', 'vocab', 'handout'];

export function parseMode(value: string | null | undefined): ModeId {
	return MODE_IDS.includes(value as ModeId) ? (value as ModeId) : 'video';
}

